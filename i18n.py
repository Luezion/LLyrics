_INDEX = {"en": 0, "es": 1, "pt": 2}


def set_lang(code):
    global _lang
    _lang = code if code in _INDEX else DEFAULT


def lang():
    return _lang


def tr(_k, **kw):
    entry = S.get(_k)
    if entry is None:
        return _k
    text = entry[_INDEX[_lang]]
    return text.format(**kw) if kw else text


def choices(items):
    """[(valor, chave_de_tradução)] -> [(valor, texto no idioma atual)]"""
    return [(v, tr(k) if k in S else k) for v, k in items]
